"""
arc.uuid7
-----------------
Time-ordered UUIDs (RFC 9562 UUIDv7) — the same scheme pgdb's own
arc_uuid_generate_v7() (plugins/pgdb/pgdb/ddl.py) stamps onto every table's
`id` column server-side by default: bytes 0-5 are a 48-bit big-endian
milliseconds-since-Unix-epoch timestamp, byte 6's high nibble is the version
(0111), byte 8's top two bits are the RFC 4122 variant (10). The 12 bits that
follow the version hold how far into that millisecond the id was made (0 to
4095, a step of about 244 nanoseconds: RFC 9562 section 6.2, method 3), and
every remaining bit is cryptographically random.

Both sides agree on the version, the variant, where the timestamp is and what
goes in the 12 bits after the version, so an id generated by either decodes
identically on the other and ids from the two sort together by time, even when
they were made within the same millisecond (on the same machine's clock). On
PostgreSQL 18 and newer the database function is a wrapper over the server's
native uuidv7(), which fills those bits in its own way; on older servers it
writes the same elapsed fraction this module does.

That keeps ids made one after another by one process in creation order. Two
things can still reorder them: the system clock being stepped backwards, and two
ids made within the same 244 nanoseconds (a call takes about a microsecond, so
one thread cannot do that; separate threads or processes can). The random bits
break such a tie arbitrarily, which is harmless because the ids are still unique.

Why this exists client-side at all, given Postgres already generates
these by default: a caller that needs a real id BEFORE the INSERT happens
(building a batch of related rows in memory, correlating a client-
generated id across two systems before either is written) has to mint one
itself rather than round-trip to the database purely to get an id.

Stateless: no project binding needed, works even before arc.boot() —
same posture as arc.codec.
"""

from __future__ import annotations

import os
import time
from datetime import datetime, timezone
from uuid import UUID

_NANOSECONDS_PER_MILLISECOND = 1_000_000
_FRACTION_STEPS = 4096  # the 12 bits after the version nibble


def generate() -> UUID:
    """A new, real UUIDv7 — sortable by creation time, in creation order
    even for ids made within the same millisecond (the 12 bits after the
    version hold the elapsed part of the millisecond), and the same layout
    pgdb/Postgres generates for a row at the same instant."""
    ms, into_ms = divmod(time.time_ns(), _NANOSECONDS_PER_MILLISECOND)
    fraction = into_ms * _FRACTION_STEPS // _NANOSECONDS_PER_MILLISECOND  # 0 .. 4095
    b = bytearray(16)
    b[0:6] = ms.to_bytes(6, "big")
    b[6:16] = os.urandom(10)
    b[6] = 0x70 | (fraction >> 8)  # version nibble 7, then the top 4 bits of the fraction
    b[7] = fraction & 0xFF  # the low 8 bits of the fraction
    b[8] = (b[8] & 0x3F) | 0x80  # RFC 4122 variant bits
    return UUID(bytes=bytes(b))


def extract_timestamp(value: UUID | str) -> datetime:
    """The real creation instant embedded in a UUIDv7 — a timezone-aware
    UTC datetime, millisecond precision (the 48-bit timestamp; the
    sub-millisecond fraction after the version is not decoded).
    Works identically on a value this module generated or one Postgres
    did (same layout either way).

    Raises ValueError if `value` isn't actually a version-7 UUID — a v4
    id has no embedded timestamp; returning a nonsense "timestamp" for
    one would be worse than refusing outright."""
    u = value if isinstance(value, UUID) else UUID(str(value))
    if u.version != 7:
        raise ValueError(f"{u} is a UUID version {u.version}, not version 7 — no timestamp to extract.")
    ms = int.from_bytes(u.bytes[:6], "big")
    return datetime.fromtimestamp(ms / 1000, tz=timezone.utc)
